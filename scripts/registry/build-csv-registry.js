#!/usr/bin/env node
/**
 * Builds a country medicine registry from a CSV/TSV export of a national list of
 * authorised medicines (e.g. Morocco AMMPS, Algeria MIPH nomenclature, Tunisia DPM,
 * Mauritania DPL, Senegal ARP…).
 *
 * Usage:
 *   node scripts/registry/build-csv-registry.js <ISO country> <file.csv> [--source "Name"] [--url URL] [--exhaustive]
 *
 * Columns are detected from the header row (case/accents ignored). Recognised names:
 *   code:        ean, ean13, gtin, barcode, code barre, code_barre, cip, cip13, code
 *   name:        name, nom, denomination, dénomination, specialite, spécialité, produit, designation
 *   holder:      holder, laboratoire, titulaire, fabricant, manufacturer, labo
 *   substances:  substances, dci, inn, principe actif, composition
 *   status:      status, statut, etat, état, commercialise, commercialisé   (optional)
 *
 * --exhaustive marks the list as complete, so a barcode issued in that country that is
 * missing from the list is flagged as "not registered". Only use it for official, complete lists.
 *
 * Output: src/data/registries/<iso>.json and an updated src/data/registries/index.ts
 */
const fs = require('fs');
const path = require('path');

const DIR = path.join(__dirname, '..', '..', 'src', 'data', 'registries');

const COLUMN_NAMES = {
  code: ['ean', 'ean13', 'gtin', 'barcode', 'code barre', 'code_barre', 'codebarre', 'cip', 'cip13', 'code'],
  name: ['name', 'nom', 'denomination', 'specialite', 'produit', 'designation', 'nom commercial'],
  holder: ['holder', 'laboratoire', 'titulaire', 'fabricant', 'manufacturer', 'labo', 'laboratoire titulaire'],
  substances: ['substances', 'substance', 'dci', 'inn', 'principe actif', 'principes actifs', 'composition'],
  status: ['status', 'statut', 'etat', 'commercialise', 'commercialisation'],
};

const norm = s => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9 _]/g, '').trim();

function decode(buf) {
  const utf8 = buf.toString('utf8').replace(/^﻿/, '');
  return utf8.includes('�') ? new TextDecoder('windows-1252').decode(buf) : utf8;
}

function parseCsv(text) {
  const firstLine = text.split(/\r?\n/, 1)[0];
  const delim = ['\t', ';', ','].sort((a, b) => firstLine.split(b).length - firstLine.split(a).length)[0];
  const rows = [];
  let row = [], cell = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (c === '"') quoted = false;
      else cell += c;
    } else if (c === '"') quoted = true;
    else if (c === delim) { row.push(cell.trim()); cell = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(cell.trim()); cell = '';
      if (row.some(Boolean)) rows.push(row);
      row = [];
    } else cell += c;
  }
  row.push(cell.trim());
  if (row.some(Boolean)) rows.push(row);
  return rows;
}

function writeIndex() {
  const countries = fs.readdirSync(DIR).filter(f => /^[a-z]{2}\.json$/.test(f)).map(f => f.slice(0, 2)).sort();
  const lines = countries.map(c => `  ${c.toUpperCase()}: () => require('./${c}.json'),`);
  fs.writeFileSync(path.join(DIR, 'index.ts'),
    `// Generated by scripts/registry/*.js — lists every bundled national medicine registry.\n`
    + `// Registries are required lazily so the app only parses the ones a scan needs.\n`
    + `import type { RegistryFile } from '../../scan/registries';\n\n`
    + `export const REGISTRY_LOADERS: Record<string, () => RegistryFile> = {\n${lines.join('\n')}\n};\n`);
}

function main() {
  const args = process.argv.slice(2);
  if (args[0] === '--index-only') { writeIndex(); return; }
  const [iso, file] = args;
  if (!/^[A-Za-z]{2}$/.test(iso || '') || !file) {
    console.error('Usage: build-csv-registry.js <ISO country> <file.csv> [--source "Name"] [--url URL] [--exhaustive]');
    process.exit(1);
  }
  const opt = name => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : undefined; };
  const rows = parseCsv(decode(fs.readFileSync(file)));
  const header = rows.shift().map(norm);
  const col = {};
  for (const [key, names] of Object.entries(COLUMN_NAMES)) {
    col[key] = header.findIndex(h => names.includes(h));
  }
  if (col.code < 0 || col.name < 0) {
    console.error(`Could not find a barcode column and a name column in: ${header.join(' | ')}`);
    process.exit(1);
  }

  const holders = [], holderIdx = new Map(), products = {}, codes = {};
  const productIdx = new Map();
  let skipped = 0;
  for (const r of rows) {
    const code = (r[col.code] || '').replace(/\D/g, '');
    const name = r[col.name];
    if (!/^\d{8,14}$/.test(code) || !name) { skipped++; continue; }
    const holder = col.holder >= 0 ? r[col.holder] || '' : '';
    if (!holderIdx.has(holder)) { holderIdx.set(holder, holders.length); holders.push(holder); }
    const status = col.status >= 0 ? norm(r[col.status] || '') : '';
    const marketed = !status || /^(oui|yes|1|commercialise|actif|active|autorise)/.test(status);
    const substances = col.substances >= 0
      ? (r[col.substances] || '').split(/[;+/,]| et /i).map(s => s.trim().toUpperCase()).filter(Boolean).join(';')
      : '';
    const key = `${name}|${holder}`;
    if (!productIdx.has(key)) {
      const id = productIdx.size;
      productIdx.set(key, id);
      products[id] = [name, holderIdx.get(holder), (marketed ? 1 : 0) | 2, substances];
    }
    codes[code.length === 14 && code.startsWith('0') ? code.slice(1) : code] = productIdx.get(key) * 4 + ((marketed ? 1 : 0) | 2);
  }

  const out = {
    meta: {
      country: iso.toUpperCase(),
      source: opt('--source') || `${iso.toUpperCase()} national medicine list`,
      url: opt('--url'),
      generatedAt: new Date().toISOString(),
      exhaustive: args.includes('--exhaustive'),
    },
    holders, products, codes,
  };
  const outFile = path.join(DIR, `${iso.toLowerCase()}.json`);
  fs.mkdirSync(DIR, { recursive: true });
  fs.writeFileSync(outFile, JSON.stringify(out));
  writeIndex();
  console.log(`[${iso.toUpperCase()}] ${Object.keys(products).length} products, ${Object.keys(codes).length} barcodes (${skipped} rows skipped) -> ${outFile}`);
}

main();
